#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""抓取远行商人页面全部商品图标，下载原图到 res/drawable-nodpi，并生成 Kotlin 映射。
图标名用 item_<i>.png，映射用商品简体名 -> R.drawable.item_<i>。
"""
import urllib.request, ssl, re, os, sys, hashlib

CTX = ssl.create_default_context(); CTX.check_hostname = False; CTX.verify_mode = ssl.CERT_NONE
HDR = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/120 Safari/537.36',
       'Referer': 'https://rocokingdomworld.org/'}

ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, 'app', 'src', 'main', 'res', 'drawable-nodpi')
os.makedirs(OUT, exist_ok=True)

PAGE = 'https://rocokingdomworld.org/zh-hant/merchant'

def fetch(url, binary=False, timeout=25):
    req = urllib.request.Request(url, headers=HDR)
    with urllib.request.urlopen(req, timeout=timeout, context=CTX) as r:
        return r.read() if binary else r.read().decode('utf-8', 'ignore')

def best_url(thumb_url):
    """thumb 缩略图 -> 尽量取原图。patchwiki 结构:
       .../images/rocom/thumb/c/c5/HASH.png/100px-100681.png
       原图: .../images/rocom/c/c5/HASH.png
    """
    # 去掉 /100px-... 后缀
    m = re.match(r'(.*/images/rocom/thumb/[a-f0-9]/[a-f0-9]/[^/]+\.png)/100px-[^/]+$', thumb_url)
    if m:
        return m.group(1)  # thumb 目录下原尺寸图
    return thumb_url

def orig_url(thumb_url):
    m = re.match(r'(.*)/images/rocom/thumb/(.)/(.)/([^/]+\.png)/100px-[^/]+$', thumb_url)
    if m:
        return f'{m.group(1)}/images/rocom/{m.group(2)}/{m.group(3)}/{m.group(4)}'
    return None

print('fetching page...', flush=True)
html = fetch(PAGE)
# 匹配 <img ... alt="商品名" ... src="图标" ...> 或 src 在前
pairs = re.findall(r'<img\b([^>]+)>', html, re.I)
items = []  # (name, url)
seen = set()
for tag in pairs:
    alt = re.search(r'alt=[\"\x27]([^\"\x27]+)[\"\x27]', tag, re.I)
    src = re.search(r'src=[\"\x27]([^\"\x27]+\.(?:png|webp|jpg|jpeg))[\"\x27]', tag, re.I)
    if not (alt and src):
        continue
    name = alt.group(1).strip()
    url = src.group(1)
    # 跳过装饰性社区贴纸，但保留 patchwiki 与 71acg 的真实物品图标
    if 'patchwiki.biligame.com/images/rocom' not in url and 'img.71acg.net' not in url:
        continue
    if name in seen:
        continue
    seen.add(name)
    items.append((name, url))

print(f'found {len(items)} merchant item icons:', flush=True)
for n, u in items:
    print('  ', n, '->', u.split('/')[-1], flush=True)

# 下载
kmap = []  # (name, drawable_name)
for i, (name, url) in enumerate(items):
    drawable = f'item_{i}'
    # 尝试原图 -> thumb原尺寸 -> 缩略
    candidates = []
    ou = orig_url(url)
    if ou: candidates.append(ou)
    candidates.append(best_url(url))
    candidates.append(url)
    ok = False
    for cu in candidates:
        try:
            data = fetch(cu, binary=True, timeout=30)
            if len(data) < 200:
                continue
            # 校验 PNG 头
            if data[:8] != b'\x89PNG\r\n\x1a\n' and not data[:3] == b'\xff\xd8\xff':
                # 可能是 svg/html 错误页
                if b'<!DOCTYPE' in data[:200] or b'<html' in data[:200]:
                    continue
            ext = 'png' if data[:8] == b'\x89PNG\r\n\x1a\n' else ('jpg' if data[:3] == b'\xff\xd8\xff' else 'png')
            fn = os.path.join(OUT, f'{drawable}.{ext}')
            with open(fn, 'wb') as f:
                f.write(data)
            print(f'  saved {drawable}.{ext} ({len(data)} bytes) from {cu.split("/")[-1]}', flush=True)
            kmap.append((name, f'R.drawable.{drawable}'))
            ok = True
            break
        except Exception as e:
            print(f'    fail {cu[:80]}: {e}', flush=True)
    if not ok:
        print(f'  !! could not download {name}', flush=True)

# 生成 Kotlin 映射片段
kotlin = '// AUTO-GENERATED by scrape_all_icons.py — 远行商人商品名 -> 图标资源\n'
kotlin += 'private val ITEM_ICONS: Map<String, Int> = mapOf(\n'
for name, res in kmap:
    kotlin += f'    "{name}" to {res},\n'
kotlin += ')\n'
with open(os.path.join(ROOT, 'item_icons_map.txt'), 'w', encoding='utf-8') as f:
    f.write(kotlin)
print('\nWROTE item_icons_map.txt with', len(kmap), 'entries', flush=True)
