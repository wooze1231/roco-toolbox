#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""批量抓取远行商人常见商品的真实图标（patchwiki 独立页原图），内置到 drawable-nodpi。
同时 seed 已验证的3个（蓝晶碧玺/魔力果/炫彩蛋）。生成 Kotlin 映射 item_icons_map.txt。
"""
import urllib.request, ssl, re, os, threading, time
from urllib.parse import quote

CTX = ssl.create_default_context(); CTX.check_hostname = False; CTX.verify_mode = ssl.CERT_NONE
HDR = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/120 Safari/537.36',
       'Referer': 'https://wiki.biligame.com/rocom/'}
ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, 'app', 'src', 'main', 'res', 'drawable-nodpi')
os.makedirs(OUT, exist_ok=True)

# 远行商人常见商品池（基于攻略整理；404/无专属图的会被跳过，APP 兜底白圆）
POOL = [
    '普通咕噜球', '中级咕噜球', '高级咕噜球', '国王球', '光合球', '调温球', '美妙球',
    '普通精灵蛋', '炫彩精灵蛋', '神奇的蛋',
    '蓝晶碧玺', '紫莲刚玉', '紫色矿石', '天使草', '石耳', '喷气菇', '星霜花', '魔力果', '彩虹果', '荧光草', '黑金', '琉璃',
    '首领血脉秘药', '地系血脉秘药', '首领血脉密钥', '炫彩精灵带', '火系血脉秘药', '水脉秘药', '草系血脉秘药',
    '萌系粉尘', '机械粉尘', '龙系粉尘', '属性粉尘', '火系粉尘', '草系粉尘', '翼系粉尘', '毒系粉尘',
    '经验果', '大经验果', '火系经验果', '水脉经验果',
    '普通材料',
]

# seed：已验证真实的图标（数据源名 -> 直接图标 URL）
SEED = {
    '炫彩蛋': 'https://img.71acg.net/whd~hykb/comm/hd_admin_upload_2982_d3f07a7c316e2b71dc3e5fc1871bd6da.png',
    '蓝晶碧玺': 'https://patchwiki.biligame.com/images/rocom/c/c5/k8wzdzechd88qs9bxuvcnyg0pv4tzl4.png',
    '魔力果': 'https://patchwiki.biligame.com/images/rocom/c/c6/5qe6rcdtfxe1gsrvgj3lrn033athx9p.png',
}

lock = threading.Lock()
kmap = []  # (name, R.drawable.item_i)
idx = 0
done_names = set()

def fetch_bytes(url, timeout=30):
    req = urllib.request.Request(url, headers=HDR)
    with urllib.request.urlopen(req, timeout=timeout, context=CTX) as r:
        return r.read()

def is_image(data):
    return data[:8] == b'\x89PNG\r\n\x1a\n' or data[:3] == b'\xff\xd8\xff'

def extract_real_icon(html):
    """从道具页 HTML 提取真实道具图标 URL（排除 Logo 与通用'图标 物品 来源'）。"""
    imgs = re.findall(r'<img\b[^>]*patchwiki\.biligame\.com/images/rocom/[^>]*>', html)
    for tag in imgs:
        src = re.search(r'src="([^"]+)"', tag)
        alt = re.search(r'alt="([^"]*)"', tag)
        if not src:
            continue
        s = src.group(1)
        a = alt.group(1) if alt else ''
        if 'Logo' in a or 'Logo' in s:
            continue
        if a == '图标 物品 来源.png':
            continue
        if '/thumb/' in s:  # 跳过缩略（通常是Logo）
            continue
        return s  # 原图直链
    return None

def worker(name):
    global idx
    with lock:
        if name in done_names:
            return
    # seed
    url = SEED.get(name)
    data = None
    if url:
        try:
            data = fetch_bytes(url)
        except Exception:
            data = None
    if data is None or not is_image(data):
        # 抓 patchwiki 页
        try:
            req = urllib.request.Request('https://wiki.biligame.com/rocom/' + quote(name), headers=HDR)
            html = urllib.request.urlopen(req, timeout=20, context=CTX).read().decode('utf-8', 'ignore')
            icon = extract_real_icon(html)
            if icon:
                data = fetch_bytes(icon)
        except Exception as e:
            with lock:
                print(f'  skip {name}: {type(e).__name__}', flush=True)
            return
    if not data or not is_image(data):
        with lock:
            print(f'  no-icon {name}', flush=True)
        return
    with lock:
        i = idx
        idx += 1
        fn = os.path.join(OUT, f'item_{i}.png')
        with open(fn, 'wb') as f:
            f.write(data)
        kmap.append((name, f'R.drawable.item_{i}'))
        done_names.add(name)
        print(f'  + {name} -> item_{i}.png ({len(data)}B)', flush=True)

print('start scraping', len(POOL), 'candidate items (+', len(SEED), 'seed) ...', flush=True)
threads = []
for n in POOL:
    t = threading.Thread(target=worker, args=(n,))
    t.start()
    threads.append(t)
    time.sleep(0.05)
for t in threads:
    t.join()

kotlin = '// AUTO-GENERATED by all_merchant_icons.py — 远行商人商品名 -> 图标资源\n'
kotlin += 'private val ITEM_ICONS: Map<String, Int> = mapOf(\n'
for name, res in kmap:
    kotlin += f'    "{name}" to {res},\n'
kotlin += ')\n'
with open(os.path.join(ROOT, 'item_icons_map.txt'), 'w', encoding='utf-8') as f:
    f.write(kotlin)
print(f'\nDONE: {len(kmap)} icons built -> item_icons_map.txt', flush=True)
